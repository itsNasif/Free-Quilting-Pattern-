// Generates minimal valid PDF files for the bundled demo patterns so the
// download flow works before real pattern files are uploaded to Supabase.
// Run: node scripts/generate-demo-pdfs.mjs
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const patterns = [
  ["cabin-in-the-pines", "Cabin in the Pines"],
  ["nine-patch-morning", "Nine Patch Morning"],
  ["flying-geese-migration", "Flying Geese Migration"],
  ["drunkards-path-noon", "Drunkard's Path at Noon"],
  ["hourglass-tides", "Hourglass Tides"],
  ["amish-diamond-patch", "Amish Diamond Patch"],
  ["broken-dishes", "Broken Dishes"],
  ["sawtooth-star-evening", "Sawtooth Star, Evening"],
];

const title = (name) =>
  `QuiltHaven${String.fromCharCode(13)}Pattern: ${name}${String.fromCharCode(13)}${String.fromCharCode(13)}This is a demo PDF generated by the QuiltHaven scaffold.${String.fromCharCode(13)}Replace it with your real pattern file in Supabase Storage.`;

function escapeText(t) {
  return t
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");
}

function buildPdf(name) {
  const stream =
    `BT /F1 20 Tf 72 720 Td (${escapeText(title(name))}) Tj ET`;
  const objects = [
    `1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj`,
    `2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj`,
    `3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj`,
    `4 0 obj\n<< /Length ${stream.length} >>\nstream\n${stream}\nendstream\nendobj`,
    `5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj`,
  ];

  let body = "%PDF-1.4\n";
  const offsets = [];
  objects.forEach((obj, i) => {
    offsets.push(body.length);
    body += `${i + 1} 0 obj\n` + obj.slice(`${i + 1} 0 obj\n`.length) + "\n";
  });

  const xrefStart = body.length;
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const off of offsets) {
    body += `${String(off).padStart(10, "0")} 00000 n \n`;
  }
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;
  return body;
}

const outDir = join(root, "public", "patterns", "demo");
mkdirSync(outDir, { recursive: true });
for (const [slug, name] of patterns) {
  const file = join(outDir, `${slug}.pdf`);
  writeFileSync(file, buildPdf(name));
  console.log(`wrote ${file}`);
}
